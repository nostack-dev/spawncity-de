import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {installShaderPrewarm,disposeShaderPrewarm,SHADER_PREWARM_VERSION} from "../sim/shader_prewarm.mjs";
const calls=[];
const renderer={gl:{LINK_STATUS:35714,getProgramParameter(program,key){calls.push({program,key});return true;}},gpu:{handle:{id:1}},render(){},lost:false,disposed:false};
const api=installShaderPrewarm(renderer);
assert.equal(globalThis.__shaderPrewarm,api);
assert.equal(api.version,SHADER_PREWARM_VERSION);
assert.equal(await api.run("effect"),true);
assert.ok(calls.length>=2,"read linked native program, don't rebuild it");
renderer.lost=true;assert.equal(await api.run("lost"),false,"context loss cannot be reported as ready");
renderer.lost=false;renderer.disposed=true;assert.equal(await api.run("disposed"),false);
renderer.disposed=false;
assert.equal(disposeShaderPrewarm({...renderer}),false,"only owner may dispose");
assert.equal(disposeShaderPrewarm(renderer),true);
assert.equal(globalThis.__shaderPrewarm,undefined);
assert.equal(await api.run("no owner"),false);
assert.throws(()=>installShaderPrewarm({}),/native WebGL2/);
const old=readFileSync("sim/shader_prewarm.mjs","utf8");
assert.doesNotMatch(old,/from ["']three["']|THREE\.|setTimeout\(|requestAnimationFrame\(|requestIdleCallback\(/);
assert.match(readFileSync("sim/native_world_presenter.mjs","utf8"),/installShaderPrewarm\(this\.renderer\)/);
console.log("Native shader-ready link: no 3D fallback, runtime loops, or shader recompile on PWA frame.");
