import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=x=>readFileSync(x,"utf8");
const core=read("sim/native_webgl2_static.mjs");
const slice=read("sim/native_city_slice.mjs");
const bootstrap=read("sim/real_world_bootstrap.mjs");
assert.ok(!/(?:from\s*["']three["']|import \* as THREE)/.test(core),"native GL backend must be independently Three-free");
assert.match(core,/createVertexArray/);
assert.match(core,/bufferSubData/,"dynamic city geometry must upload into existing GPU allocation");
assert.match(core,/deleteVertexArray/);
assert.match(core,/deleteProgram/);
assert.match(slice,/gl\.bindFramebuffer\(gl\.FRAMEBUFFER,null\)/);
assert.match(slice,/gl\.depthMask\(true\)/);
assert.match(slice,/renderer\.resetState\(\)/);
assert.match(slice,/clear:false/,"native city must respect the already-drawn game's depth buffer");
assert.match(slice,/this\.sources/);
assert.match(slice,/this\.native\.update/);
assert.match(bootstrap,/get\("render"\)==="native-city"/,"debug renderer must be opt-in and not replace the default rendering");
assert.match(bootstrap,/this\.nativeCityDisabled=true/);
assert.match(bootstrap,/nativeCityError=error;this\.nativeCityDisabled=true;\s*renderer\.render\(scene,camera\)/);
assert.match(bootstrap,/this\.nativeCitySlice\.restore\(\)/);
assert.ok(!bootstrap.includes('get("render")!=="quality"'),"default quality must remain intact");
console.log("Native city vertical-slice regression passed: opt-in only; buffers, depth and fallback protected.");
