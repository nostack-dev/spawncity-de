import assert from "node:assert/strict";
import {multiply4,perspective,lookAt,fromTRS} from "../sim/native_render_math.mjs";
import {extractFrustumPlanes,sphereVisible,geometryBoundingSphere,instancedBoundingSphere} from "../sim/native_render_culling.mjs";
const m=multiply4(perspective(Math.PI/2,1,.2,300),lookAt([0,-10,3],[0,0,3],[0,0,1]));
const p=extractFrustumPlanes(m);
assert.equal(p.length,6);
assert.ok(sphereVisible(p,[0,0,3],1),"center world must be visible");
assert.equal(sphereVisible(p,[0,-50,3],.3),false,"behind camera must cull");
assert.equal(sphereVisible(p,[900,0,3],1),false,"lateral outside frustum must cull");
assert.equal(sphereVisible(p,[0,1000,3],1),false,"beyond far plane must cull");
assert.ok(sphereVisible(p,[0,0,3],800),"large objects crossing frustum must stay visible");
const local=geometryBoundingSphere(new Float32Array([-1,-1,0,1,-1,0,1,1,2,-1,-1,0,1,1,2,-1,1,2]));
assert.deepEqual(local.center,[0,0,1]);
assert.ok(local.radius>=Math.sqrt(3));
const front=instancedBoundingSphere(local,fromTRS([0,0,2],[0,0,0,1],[2,2,6]));
assert.ok(sphereVisible(p,front.center,front.radius));
const far=instancedBoundingSphere(local,fromTRS([9000,9000,9000]));
assert.equal(sphereVisible(p,far.center,far.radius),false);
const overlap=instancedBoundingSphere(local,new Float32Array([...fromTRS([0,0,3]),...fromTRS([9000,9000,9000])]));
assert.ok(sphereVisible(p,overlap.center,overlap.radius),"must never cull group with even one visible instance");
assert.throws(()=>geometryBoundingSphere(new Float32Array([NaN,0,0,1,0,0,0,1,0])));
assert.throws(()=>sphereVisible([],[],1));
console.log("Native world frustum and conservative instanced bounds passed.");
