import assert from "node:assert/strict";
import {NativeSceneGraph} from "../sim/native_scene_graph.mjs";
const calls=[],positions=new Map(),visibility=new Map();
const gpu={
 updateInstances(id,{transforms}){assert.ok(transforms instanceof Float32Array);assert.equal(transforms.length,16);positions.set(id,[...transforms]);calls.push(["matrix",id]);},
 setVisible(id,visible){visibility.set(id,visible);calls.push(["visibility",id,visible]);},
 remove(id){visibility.delete(id);positions.delete(id);calls.push(["gpu-delete",id]);return true;}
};
const graph=new NativeSceneGraph(gpu);
graph.add("car",{position:[10,2,1]});
graph.add("cockpit",{parent:"car",meshId:"car/seat",position:[1,0,1]});
graph.add("head",{parent:"cockpit",meshId:"car/head",position:[0,0,.5]});
graph.add("rotor",{meshId:"drone/rotor",position:[0,0,5]});
assert.throws(()=>graph.add("dupe",{meshId:"drone/rotor"}),/already owned/,"one GPU mesh must not be controlled by two scene nodes");
let stats=graph.sync();
assert.equal(stats.nodes,4);assert.equal(stats.worldMatrices,4);
assert.equal(positions.get("car/seat")[12],11);
assert.equal(positions.get("car/head")[14],2.5);
assert.equal(visibility.get("car/seat"),true);
assert.equal(visibility.get("drone/rotor"),true);
const idle=graph.sync();assert.equal(idle.worldMatrices,0);
assert.equal(calls.filter(x=>x[0]==="matrix").length,3,"stationary objects must not write GPU transform data twice");
assert.equal(graph.setTransform("car",{position:[10,2,1]}),false,"same Box3D pose must not schedule more GPU buffer writes");
assert.throws(()=>graph.setTransform("car",{position:[99,0,0],rotation:[0,0,0,0]}),/degenerate rotation/);
assert.equal(graph.require("car").position[0],10,"invalid pose must not partially mutate world state");
assert.equal(graph.sync().worldMatrices,0,"invalid/unchanged poses cannot trigger GPU updates");
graph.setTransform("car",{position:[20,2,1]});
stats=graph.sync();
assert.equal(stats.worldMatrices,3,"changing a root only dirties its own hierarchy");
assert.equal(positions.get("car/seat")[12],21);
assert.equal(positions.get("car/head")[12],21);
graph.setTransform("car",{rotation:[0,0,Math.SQRT1_2,Math.SQRT1_2]});
graph.sync();
assert.ok(Math.abs(positions.get("car/seat")[12]-20)<1e-5,"parent yaw must rotate cockpit mount");
assert.ok(Math.abs(positions.get("car/seat")[13]-3)<1e-5,"child translation inherits quaternion heading");
graph.setTransform("car",{rotation:[0,0,0,1]});graph.sync();
assert.equal(calls.filter(x=>x[0]==="matrix"&&x[1]==="drone/rotor").length,1);
graph.setVisible("car",false);graph.sync();
assert.equal(visibility.get("car/seat"),false);
assert.equal(visibility.get("car/head"),false);
assert.equal(visibility.get("drone/rotor"),true);
graph.setTransform("car",{position:[27,3,1]});
graph.sync();assert.equal(positions.get("car/seat")[12],21,"hidden hierarchy must not upload offscreen positions");
graph.setVisible("car",true);graph.sync();
assert.equal(visibility.get("car/head"),true);
assert.equal(positions.get("car/seat")[12],28);
graph.setParent("head","rotor");
graph.sync();
assert.equal(positions.get("car/head")[12],0);
assert.equal(positions.get("car/head")[14],5.5);
assert.throws(()=>graph.setParent("car","cockpit"),/cycle/);
assert.throws(()=>graph.setParent("rotor","rotor"),/cycle/);
assert.throws(()=>graph.add("rotor"),/unique/);
assert.throws(()=>graph.add("missing",{parent:"not-there"}),/unknown/);
assert.equal(graph.remove("car"),2);
assert.ok(calls.some(x=>x[0]==="gpu-delete"&&x[1]==="car/seat"),"removing vehicle must free its native GPU buffers");
assert.equal(graph.meshOwners.has("car/seat"),false,"ownership must be released on despawn");
graph.add("replacement",{meshId:"car/seat"});
graph.sync();assert.ok(graph.meshOwners.has("car/seat"),"GPU name can be safely reused after despawn");
assert.equal(visibility.get("car/seat"),false);
assert.ok(graph.nodes.has("head"),"reparented attachment survives removed original car");
assert.equal(graph.remove("rotor"),2);
graph.dispose();graph.dispose();
assert.equal(graph.meshOwners.size,0);
assert.ok(calls.some(x=>x[0]==="gpu-delete"&&x[1]==="car/head"),"disposal must release reparented actor buffers");
assert.ok(calls.some(x=>x[0]==="gpu-delete"&&x[1]==="drone/rotor"),"disposal must release GPU rotor buffers");
assert.ok(calls.some(x=>x[0]==="gpu-delete"&&x[1]==="car/seat"),"disposal must release reused GPU buffers");
assert.throws(()=>graph.add("after"),/disposed/);
console.log("Native exclusive scene graph: parent and child transforms, hidden meshes, render submission dedup, reparent cycles and safe GPU cleanup passed.");
