import assert from "node:assert/strict";
import {screenRay,pickNativeMeshes} from "../sim/native_scene_picking.mjs";
import {fromTRS} from "../sim/native_render_math.mjs";
import {geometryBoundingSphere,instancedBoundingSphere} from "../sim/native_render_culling.mjs";
const near=(a,b,eps=1e-4)=>assert.ok(Math.abs(a-b)<eps,"expected "+b+" got "+a);
const camera={eye:[0,-10,2],target:[0,0,2],up:[0,0,1],fov:Math.PI/3,near:.1,far:100};
const ray=screenRay(camera,480,270,960,540);
near(ray.direction[0],0);near(ray.direction[1],1);near(ray.direction[2],0);
const left=screenRay(camera,0,270,960,540);
assert.ok(left.direction[0]<0,"left screen must yield left ray");
const up=screenRay(camera,480,0,960,540);
assert.ok(up.direction[2]>0,"top screen must yield upward ray");
const positions=new Float32Array([-2,0,0,2,0,0,2,0,4,-2,0,4]);
const indices=new Uint16Array([0,1,2,0,2,3]);
const transforms=fromTRS([0,0,0]);
const localBounds=geometryBoundingSphere(positions);
function node(id,{transforms=fromTRS([0,0,0]),visible=true,skin=null,doubleSided=false}={}){
 return {id,visible,material:{doubleSided},worldBounds:instancedBoundingSphere(localBounds,transforms),
  data:{p:positions,indices,transforms,skin,count:transforms.length/16}};
}
const nearWall=node("wall");
const distantWall=node("far",{transforms:fromTRS([0,4,0])});
const offscreenWall=node("outside",{transforms:fromTRS([300,0,0])});
const map=new Map([["far",distantWall],["outside",offscreenWall],["wall",nearWall]]);
const hit=pickNativeMeshes(map,ray,{maxDistance:80});
console.log("NATIVE_PICK_DEBUG",JSON.stringify({ray,hit,mesh:nearWall.data.transforms.slice(0,16)}));
assert.equal(hit.hit?.id,"wall","closest matching wall must win");
near(hit.hit.distance,10);near(hit.hit.point[0],0);near(hit.hit.point[1],0);near(hit.hit.point[2],2);
near(hit.hit.normal[1],-1);
assert.equal(hit.boundsRejected,1,"distant lateral object should fail sphere bound");
const ignore=pickNativeMeshes(map,ray,{ignoreId:"wall"});
assert.equal(ignore.hit?.id,"far");near(ignore.hit.distance,14);
const skipInvisible=pickNativeMeshes([node("hidden",{visible:false})],ray);
assert.equal(skipInvisible.hit,null);
const noHit=pickNativeMeshes(map,ray,{maxDistance:4});
assert.equal(noHit.hit,null);
const moved=pickNativeMeshes([node("instance",{transforms:new Float32Array([...fromTRS([200,0,0]),...fromTRS([0,7,0])])})],ray);
assert.equal(moved.hit?.instance,1);near(moved.hit?.distance,17);
const animated=pickNativeMeshes([node("actor",{skin:{bones:new Float32Array(16)}})],ray);
assert.equal(animated.hit,null);assert.equal(animated.skippedSkinned,1,"stale animation pose must not produce false hits");
assert.throws(()=>screenRay(camera,0,0,0,1080),/viewport/);
assert.throws(()=>pickNativeMeshes([], {origin:[0,0,0],direction:[0,0,0]}),/direction/);
console.log("Native ray picking: screen centre/edges, closest indexed wall, instanced offset, bounds rejection and animation safety passed.");
