import assert from "node:assert/strict";
import {nativeCurrentGameMode,nativeGameplayCamera} from "../sim/native_gameplay_camera.mjs";
import {VsPoseTimeline} from "../sim/vs_pose_sync.mjs";

const near=(a,b,why)=>assert.ok(Math.abs(a-b)<1e-4,`${why||"mismatch"}: ${a} vs ${b}`);
const p3=(p,w,label)=>p.forEach((n,i)=>near(n,w[i],label+" axis "+i));
const walk={mode:"foot",position:{x:7,y:-3,z:1.68},yaw:0,pitch:0};
const car={active:false,speedMps:10,pose:{position:[10,-5,1],rotation:[0,0,0,1],yaw:0}};
const jet={active:false,cockpit:true,pose:{x:2,y:3,z:100,q:[0,0,0,1]}};
const timeline=new VsPoseTimeline({delayMs:0});
const world={mode:"auto",walk,car,jet,peerTimeline:timeline};
assert.equal(nativeCurrentGameMode(world),"foot");
let view=nativeGameplayCamera(world,{aspect:16/9,now:1000});
assert.equal(view.mode,"foot");
p3(view.camera.eye,[7,-3,1.68],"real foot-eye");
p3(view.camera.target,[7,9,1.68],"foot yaw 0 faces +Y");
near(view.camera.fov,2*Math.atan(1/(16/9)),"FPS 90 horizontal FOV");
walk.yaw=Math.PI/2;
view=nativeGameplayCamera(world,{aspect:1,now:1016});
p3(view.camera.target,[19,-3,1.68],"foot yaw positive faces +X");
walk.pitch=.25;world.adsZoom=2;
view=nativeGameplayCamera(world,{aspect:16/9,now:1032});
assert.ok(view.camera.target[2]>view.camera.eye[2],"FPS pitch uses actual player state");
assert.ok(view.camera.fov<2*Math.atan(1/(16/9)),"sights scope narrows actual camera FOV");
car.active=true;
assert.equal(nativeCurrentGameMode(world),"car","car overrides foot provider");
view=nativeGameplayCamera(world,{aspect:16/9,now:1040});
p3(view.camera.target,[11.05,-5,2.2],"car target matches body heading +X");
p3(view.camera.eye,[6.05,-5,4.4],"car follows the authoritative interpolated Box3D pose");
car.pose.position[0]=18;
assert.equal(nativeGameplayCamera(world,{now:1050}).camera.target[0],19.05);
world.carCameraMode="cockpit";
view=nativeGameplayCamera(world,{now:1050});
p3(view.camera.eye,[18.04,-4.64,2.24],"car cockpit is body-attached");
assert.ok(view.camera.target[0]>view.camera.eye[0]);
jet.active=true;
assert.equal(nativeCurrentGameMode(world),"jet","jet has priority over driving");
view=nativeGameplayCamera(world,{now:1060});
assert.equal(view.mode,"jet");
p3(view.camera.eye,[2,6.5,101.42],"jet cockpit uses authentic local 0,3.5,1.42");
assert.ok(view.camera.target[1]>view.camera.eye[1],"jet forward is local +Y");
assert.equal(view.camera.far,20000);
jet.cockpit=false;jet.state={speed:0};
view=nativeGameplayCamera(world,{now:1070});
p3(view.camera.eye,[2,-19,106.5],"jet chase 22 m behind and 6.5 m above");
jet.pose.para=1;
view=nativeGameplayCamera(world,{now:1075});
p3(view.camera.eye,[2,-11,107],"parachute camera is independent of powered flight");
delete jet.pose.para;jet.occupantSeat="passenger";
view=nativeGameplayCamera(world,{now:1078});
p3(view.camera.eye,[2.48,5.5,101.25],"passenger seat follows jet quaternion");
world.mode="drone";
view=nativeGameplayCamera(world,{now:1080});
assert.equal(view.mode,"drone");
assert.equal(view.camera,null,"drone FPV/follow is owned exclusively by existing native 1kHz airframe");
world.mode="multiplayer";
assert.throws(()=>nativeGameplayCamera(world,{now:1080}),/VsPoseTimeline/);
assert.equal(timeline.push({p:[2,4,10],q:[0,0,0,1],v:[0,0,0],t:1100},1100),true);
view=nativeGameplayCamera(world,{now:1100});
assert.equal(view.mode,"multiplayer");
p3(view.camera.eye,[7,4,12],"remote camera samples original networked drone quaternion");
assert.ok(view.camera.target[0]<view.camera.eye[0],"peer spectator looks along drone -X");
world.mode="auto";jet.active=false;car.active=false;walk.mode="drone";
assert.equal(nativeCurrentGameMode(world),"drone","inactive modes cannot steal the drone camera");
assert.throws(()=>nativeGameplayCamera({...world,mode:"foot"}),/__arondightWalkMode/);
assert.throws(()=>nativeCurrentGameMode({mode:"unknown"}),/invalid native game mode/);
assert.throws(()=>nativeGameplayCamera({...world,mode:"car"}),/__arondightVehicleDrive/);
assert.throws(()=>nativeGameplayCamera({...world,mode:"jet"}),/__jetMode/);
assert.throws(()=>nativeGameplayCamera({...world,mode:"multiplayer"},{aspect:0}),/viewport/);
assert.throws(()=>nativeGameplayCamera({...world,mode:"foot",walk:{...walk,mode:"foot",position:{x:NaN,y:0,z:0}}}),/finite XYZ/);
console.log("native full-game cameras: drone, foot, physical car/cockpit, jet/passenger/parachute, network spectator – real states and mode precedence");
