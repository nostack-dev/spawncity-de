import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {isInstalledGameApp,shouldRequestGameFullscreen} from "../sim/pwa_fullscreen_policy.mjs";
const check=(sample,want)=>assert.equal(shouldRequestGameFullscreen(sample),want,JSON.stringify(sample));
check({displayModeFullscreen:true,apiAvailable:true},false);
check({displayModeStandalone:true,apiAvailable:true},false);
check({iosStandalone:true,apiAvailable:true},false);
check({alreadyFullscreen:true,apiAvailable:true},false);
check({apiAvailable:false},false);
check({apiAvailable:true},true);
check({displayModeFullscreen:false,displayModeStandalone:false,apiAvailable:true},true);
assert.equal(isInstalledGameApp({fullscreen:true}),true);
assert.equal(isInstalledGameApp({standalone:true}),true);
assert.equal(isInstalledGameApp({iosStandalone:true}),true);
assert.equal(isInstalledGameApp({}),false);
const sim=readFileSync("sim/simulator.mjs","utf8");
const manifest=JSON.parse(readFileSync("drone_simulator.webmanifest","utf8"));
assert.equal(manifest.display,"fullscreen");
assert.equal(manifest.orientation,"landscape");
assert.match(sim,/shouldRequestGameFullscreen\(\{/);
assert.match(sim,/display-mode: fullscreen/);
assert.match(sim,/display-mode: standalone/);
assert.doesNotMatch(sim,/100svh!important/,"small viewport units leave PWA display black bars");
assert.match(sim,/html\.android-stable-webgl body\.solo-flight #viewport\{height:100dvh!important\}/);
assert.match(sim,/html\.android-stable-webgl body\.solo-flight #viewport\{width:100dvh!important/);
assert.match(sim,/document\.documentElement\.requestFullscreen\(\{navigationUI:"hide"\}\)/);
console.log("Android/iOS installed PWA: true viewport and no redundant Fullscreen OS toast.");
